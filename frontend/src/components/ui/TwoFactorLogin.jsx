import React, { useState } from 'react';
import Modal from './Modal';
import Input from './Input';
import Button from './Button';
import { ShieldCheck } from 'lucide-react';
import toast from 'react-hot-toast';

const TwoFactorLogin = ({ isOpen, onClose, onVerify }) => {
  const [code, setCode] = useState('');
  const [isLoading, setIsLoading] = useState(false);

  const handleSubmit = async (e) => {
    e.preventDefault();
    if (code.length !== 6) {
      toast.error('Please enter a valid 6-digit code.');
      return;
    }
    
    setIsLoading(true);
    // Simulate API call for 2FA verification
    setTimeout(() => {
      setIsLoading(false);
      onVerify(code);
    }, 1000);
  };

  return (
    <Modal isOpen={isOpen} onClose={onClose} title="Two-Factor Authentication">
      <form onSubmit={handleSubmit} className="p-6 space-y-6 font-normal">
        <div className="flex flex-col items-center text-center space-y-3 font-normal">
          <div className="w-16 h-16 bg-brand-50 text-brand-600 rounded-full flex items-center justify-center font-normal">
            <ShieldCheck className="w-8 h-8 font-normal" />
          </div>
          <h3 className="text-xl font-bold text-text-primary">Verification Required</h3>
          <p className="text-sm text-text-muted font-medium">
            Enter the 6-digit verification code generated by your authenticator app.
          </p>
        </div>
        
        <div>
          <Input 
            label="Verification Code" 
            type="text" 
            maxLength={6}
            value={code} 
            onChange={(e) => setCode(e.target.value.replace(/\D/g, ''))} 
            placeholder="000000"
            className="text-center text-2xl tracking-[0.5em] font-mono"
            required
            autoFocus
          />
        </div>

        <Button type="submit" className="w-full font-normal" isLoading={isLoading} disabled={code.length !== 6}>
          Verify Identity
        </Button>
      </form>
    </Modal>
  );
};

export default TwoFactorLogin;
