from typing import List, Optional
from pydantic import BaseModel, Field

class PendingState(BaseModel):
    awaiting: str
    search_term: Optional[str] = None
    category: Optional[str] = None

class ChatMessage(BaseModel):
    role: str = Field(..., description="The role of the message sender, either 'user' or 'assistant'.")
    content: str = Field(..., description="The content of the message.")

class ConversationMetadata(BaseModel):
    conversationStarted: bool = Field(False, description="Whether the conversation has already started.")
    conversationStatus: str = Field("NEW", description="Status of conversation: NEW, ACTIVE, IDLE, ENDED, HANDOFF")
    greetingCount: int = Field(0, description="The number of times the user has greeted.")
    messageCount: int = Field(0, description="The total number of messages in the session.")
    lastGreeting: Optional[str] = Field(None, description="The last greeting used by the user.")
    lastDetectedIntent: Optional[str] = Field(None, description="The last detected intent.")
    lastHandler: Optional[str] = Field(None, description="The last handler used.")
    lastUserMessageAt: float = Field(0.0, description="Timestamp of last user message.")
    lastBotMessageAt: float = Field(0.0, description="Timestamp of last bot message.")
    lastInteractionAt: float = Field(0.0, description="Timestamp of last interaction.")
    sessionStartedAt: float = Field(0.0, description="Timestamp when session started.")
    conversationStartedAt: Optional[float] = Field(None, description="Timestamp when conversation started.")
    isAuthenticated: bool = Field(False, description="Whether the user is authenticated (frontend).")
    userId: Optional[str] = Field(None, description="The user's ID (frontend).")
    is_authenticated: bool = Field(False, description="Whether the user is authenticated (backend).")
    user_id: Optional[str] = Field(None, description="The user's ID (backend).")
    pendingState: Optional[PendingState] = None

class RequestContext(BaseModel):
    """Unified context passed through the Fast Path pipeline."""
    raw_message: str
    normalized_message: str
    conversation_id: str
    session_id: str
    message_count: int
    conversation_started: bool
    conversation_status: str
    greeting_count: int
    last_greeting: Optional[str]
    last_detected_intent: Optional[str]
    last_handler: Optional[str]
    last_user_message_at: float
    last_bot_message_at: float
    last_interaction_at: float
    session_started_at: float
    conversation_started_at: Optional[float]
    canonical_greeting: Optional[str] = None
    canonical_thanks: Optional[str] = None
    faq_answer: Optional[str] = None
    timestamp: float
    identity_result: Optional["IdentityResult"] = None
    order_status_result: Optional["OrderStatusResult"] = None
    product_search_result: Optional["ProductSearchResult"] = None
    is_authenticated: bool = False
    user_id: Optional[str] = None
    pending_state: Optional[PendingState] = None

class IdentityResult(BaseModel):
    """Structured result from the IdentityDetector."""
    is_identity: bool


class GibberishResult(BaseModel):
    """Structured result from the GibberishDetector."""
    is_gibberish: bool
    score: int
    reasons: List[str]

class GreetingResult(BaseModel):
    """Structured result from the GreetingDetector."""
    is_greeting: bool
    canonical_greeting: Optional[str] = None

class ThanksResult(BaseModel):
    """Structured result from the ThanksDetector."""
    is_thanks: bool
    canonical_thanks: Optional[str] = None

class OrderStatusResult(BaseModel):
    """Structured result from the OrderStatusDetector."""
    is_order_status: bool
    order_id: Optional[str] = None

class ProductSearchResult(BaseModel):
    """Structured result from the ProductSearchDetector."""
    is_product_search: bool
    search_term: Optional[str] = None
    category: Optional[str] = None
    min_price: Optional[float] = None
    max_price: Optional[float] = None

class FAQResult(BaseModel):
    """Structured result from the FAQDetector."""
    is_faq: bool
    matched_question: Optional[str] = None
    answer: Optional[str] = None
    confidence: Optional[float] = None

class ChatRequest(BaseModel):
    message: str = Field(..., min_length=1, description="The message sent by the user to the chatbot.")
    history: List[ChatMessage] = Field(default_factory=list, description="The conversation history so far.")
    metadata: Optional[ConversationMetadata] = Field(default_factory=ConversationMetadata, description="Contextual metadata for the conversation.")

class ChatResponse(BaseModel):
    reply: str = Field(..., description="The textual response generated by the chatbot.")
    type: str = Field(..., description="The classification type of the response (e.g., greeting, gibberish, default, RAG, etc.).")
    action: Optional[str] = None
    orders: Optional[List[dict]] = None
    pending_state: Optional[PendingState] = None
    products: Optional[List[dict]] = None
    category: Optional[str] = None
